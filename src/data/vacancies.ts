const REPORT_MS = new Date(VACANCY_REPORT_DATE).getTime();

export const vacancyMonths = (v: Vacancy): number | null =>
  v.since ? (REPORT_MS - new Date(v.since).getTime()) / (1000 * 60 * 60 * 24 * 30.44) : null;

export const VAC_POSITIONS = VACANCIES.length;
export const VAC_PEOPLE = VACANCIES.reduce((s, v) => s + v.count, 0);

export const VAC_AGE_BANDS = [
  { band: 'до 3 месяцев', color: '#16a34a', min: 0, max: 3 },
  { band: '3–6 месяцев', color: '#f59e0b', min: 3, max: 6 },
  { band: '6–12 месяцев', color: '#f97316', min: 6, max: 12 },
  { band: 'больше года', color: '#dc2626', min: 12, max: Infinity },
].map((b) => {
  const items = VACANCIES.filter((v) => {
    const m = vacancyMonths(v);
    return m !== null && m >= b.min && m < b.max;
  });
  return {
    ...b,
    positions: items.length,
    people: items.reduce((s, v) => s + v.count, 0),
  };
});

export const VAC_OLD_PEOPLE = VAC_AGE_BANDS.filter((b) => b.min >= 6).reduce((s, b) => s + b.people, 0);
export const VAC_FRESH_PEOPLE = VAC_AGE_BANDS[0].people;

export const VAC_DEPTS = Object.entries(
  VACANCIES.reduce<Record<string, number>>((acc, v) => {
    const key = v.dept.startsWith('ПТИ')
      ? 'ПТИ'
      : v.dept.includes('СМТ')
        ? 'СМТ'
        : v.dept.includes('СИВ')
          ? 'Отдел проектирования СИВ'
          : v.dept === 'УГП'
            ? 'УГП'
            : v.dept === 'Не указано'
              ? 'Без подразделения'
              : 'Прочие';
    acc[key] = (acc[key] || 0) + v.count;
    return acc;
  }, {}),
)
  .map(([dept, people]) => ({ dept, people }))
  .sort((a, b) => b.people - a.people);

const withSalary = VACANCIES.filter((v) => v.salaryMin !== null);
export const VAC_SALARY_AVG = Math.round(
  withSalary.reduce((s, v) => s + (v.salaryMin as number), 0) / withSalary.length / 1000,
);
export const VAC_TOP_SALARY = Math.max(...withSalary.map((v) => v.salaryMin as number));
export const VAC_MONTHLY_BUDGET = Math.round(
  withSalary.reduce((s, v) => s + (v.salaryMin as number) * v.count, 0) / 1000000,
);
